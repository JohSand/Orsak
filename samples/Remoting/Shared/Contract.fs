/// The contract the server and the browser share: the side effect of keeping todos, as an Orsak interface, its
/// provider, and the effects created from it. [<GenRemote>] generates the proxy, TodoApiProxy, at the end of this file.
module Todos.Shared.Contract

open System.Threading.Tasks
open Orsak
open Orsak.Remoting

type Todo = { Id: int; Title: string; Done: bool }

/// The contract's errors, which cross the wire as values.
type TodoError =
    | EmptyTitle
    | NotFound of id: int
    | AlreadyDone of id: int

/// Keeping todos, wherever it happens: on the server, a store; in the browser, calls to the server.
[<GenRemote>]
type ITodoApi =
    abstract List: unit -> Task<Todo list>
    abstract Add: title: string -> Task<Result<Todo, TodoError>>
    abstract Complete: id: int -> Task<Result<Todo, TodoError>>

type ITodoApiProvider =
    abstract TodoApi: ITodoApi

/// The effects of the contract. An effect built from them doesn't know where it runs.
module TodoApi =
    let list () =
        Effect.Create(fun (p: #ITodoApiProvider) -> p.TodoApi.List())

    let add title =
        Effect.Create(fun (p: #ITodoApiProvider) -> p.TodoApi.Add title)

    let complete id =
        Effect.Create(fun (p: #ITodoApiProvider) -> p.TodoApi.Complete id)
