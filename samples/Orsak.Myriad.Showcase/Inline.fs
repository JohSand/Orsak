[<GenEffects>]
type IClock =
    abstract Now: unit -> DateTimeOffset

type IGreeter =
    abstract Greet: string -> string

type IGreeterProvider =
    abstract Effect: IGreeter

/// An ad hoc environment, inheriting IClockProvider, which is generated further down this file.
[<GenEnvironment>]
type IInlineEnvironment =
    inherit IClockProvider
    inherit IGreeterProvider

let greet name =
    Effect.Create(fun (provider: #IGreeterProvider) -> provider.Effect.Greet name)

/// Uses the generated InlineEnvironment.create, declared below. Its signature is fully annotated, so the
/// rec module can use it above its declaration; generated effect functions like Clock.now are inferred,
/// so they are used from a later file instead (Program.fs).
let environment () =
    InlineEnvironment.create {|
        Clock = { new IClock with member _.Now() = DateTimeOffset(2026, 9, 23, 12, 0, 0, TimeSpan.Zero) }
        Greeter = { new IGreeter with member _.Greet name = $"Hello {name}" }
    |}

type ILocale =
    abstract Culture: string

type ILocaleProvider =
    abstract Effect: ILocale

/// Extends IInlineEnvironment with a locale, the way the environment of a scope extends the application's. As it
/// inherits one other environment from this file, it also gets LocalizedEnvironment.extend.
[<GenEnvironment>]
type ILocalizedEnvironment =
    inherit IInlineEnvironment
    inherit ILocaleProvider

/// Uses the generated LocalizedEnvironment.extend, which forwards the providers of the environment it extends.
let localized () =
    LocalizedEnvironment.extend (environment ()) {| Locale = { new ILocale with member _.Culture = "sv-SE" } |}

type IUnitOfWork =
    inherit CompletableScope
    abstract Record: string -> unit

type IUnitOfWorkProvider =
    abstract Effect: IUnitOfWork

/// Grows into IWorkEnvironment in a scope of IUnitOfWork. The generator implements Grow with
/// WorkEnvironment.extend, and BeginScope with a field of the record of effects.
[<GenEnvironment>]
type IAppEnvironmentWithWork =
    inherit IGreeterProvider
    inherit CompletableScopeProvider<IUnitOfWork>
    inherit IGrowsInto<IUnitOfWork, IWorkEnvironment>

/// The environment in a unit of work: the application's, and the unit of work.
and [<GenEnvironment>] IWorkEnvironment =
    inherit IAppEnvironmentWithWork
    inherit IUnitOfWorkProvider

/// A unit of work that records what happens to it in log.
let unitOfWork (log: ResizeArray<string>) =
    { new IUnitOfWork with
        member _.Record entry = log.Add entry

        member _.Complete() =
            log.Add "completed"
            Threading.Tasks.ValueTask()

        member _.DisposeAsync() =
            log.Add "disposed"
            Threading.Tasks.ValueTask() }

let environmentWithWork (log: ResizeArray<string>) =
    AppEnvironmentWithWork.create {|
        Greeter = { new IGreeter with member _.Greet name = $"Hello {name}" }
        UnitOfWorkScope =
            { new CompletableScopeProvider<IUnitOfWork> with
                member _.BeginScope() = Threading.Tasks.ValueTask<_>(unitOfWork log) }
    |}
