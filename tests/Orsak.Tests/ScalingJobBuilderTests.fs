type ICounter =
    abstract member Count: unit -> unit

type ICounterProvider =
    abstract member Effect: ICounter

[<GenEnvironment>]
type ITestEnvironment =
    inherit ICounterProvider

[<GenEnvironment>]
type IJobTestEnvironment =
    inherit ITestEnvironment
    inherit ICancellationProvider

type CounterEnv(counter: ICounter) =
    interface ICounterProvider with
        member _.Effect = counter

module Counter =
    let count () =
        Effect.Create(fun (er: #ICounterProvider) -> er.Effect.Count())

let countOnce () = eff {
    do! Counter.count ()
    do! Task.Delay 1
    return ()
}

let handleCounting () : Effect<CounterEnv, unit, string> = countOnce ()

let createEnvironment (services: IServiceProvider) (_: CancellationToken) =
    CounterEnv(services.GetRequiredService<ICounter>())

[<Fact>]
let ``scalingJob is named after its work function`` () =
    let job = scalingJob {
        work handleCounting
        environment createEnvironment
    }

    job.Name =! "handleCounting"

[<Fact>]
let ``namedScalingJob keeps its own name`` () =
    let job = namedScalingJob "counting" {
        work handleCounting
        environment createEnvironment
    }

    job.Name =! "counting"

/// Records the source of each run's environment.
let recordSources (sources: System.Collections.Concurrent.ConcurrentQueue<CancellationTokenSource>) () = eff {
    let! source = Effect.Create(fun (p: IJobTestEnvironment) -> p.Source)
    sources.Enqueue source
    do! countOnce ()
}

[<Fact(Timeout = 10_000)>]
let ``scalingJob2 runs each run of its work in a cancellation scope of its own`` () = task {
    let sources = System.Collections.Concurrent.ConcurrentQueue<CancellationTokenSource>()

    let counter = {
        new ICounter with
            member _.Count() = ()
    }

    let environment = TestEnvironment.create {| Counter = counter |}

    let job = scalingJob2 environment.Extend {
        work (recordSources sources)
    }

    use services = ServiceCollection().AddLogging().AddScalingJob(job).BuildServiceProvider()
    let hosted = services.GetServices<IHostedService>() |> Seq.exactlyOne
    do! hosted.StartAsync CancellationToken.None
    let clock = Stopwatch.StartNew()

    while sources.Count < 3 && clock.Elapsed < TimeSpan.FromSeconds 5. do
        do! Task.Delay 5

    do! hosted.StopAsync CancellationToken.None

    let seen = List.ofSeq sources
    Assert.True(seen.Length >= 3, $"only {seen.Length} runs")
    Assert.All(seen, fun s -> Assert.IsType<CancellationScope>(s) |> ignore)
    Assert.Equal(seen.Length, (List.distinct seen).Length)
    // every run has ended, so every scope is disposed
    for source in seen do
        Assert.Throws<ObjectDisposedException>(fun () -> source.Token |> ignore) |> ignore
}

[<Fact(Timeout = 10_000)>]
let ``a scaling job added to the services runs its work`` () = task {
    let mutable count = 0

    let counter = {
        new ICounter with
            member _.Count() = Interlocked.Increment &count |> ignore
    }

    let job = scalingJob {
        work handleCounting
        environment createEnvironment
        workload (fun _ _ -> Task.FromResult Sustained)
        maxExtraWorkers 2
    }

    use services =
        ServiceCollection().AddLogging().AddSingleton<ICounter>(counter).AddScalingJob(job).BuildServiceProvider()

    let hosted = services.GetServices<IHostedService>() |> Seq.exactlyOne
    do! hosted.StartAsync CancellationToken.None
    let clock = Stopwatch.StartNew()

    while count < 3 && clock.Elapsed < TimeSpan.FromSeconds 5. do
        do! Task.Delay 5

    do! hosted.StopAsync CancellationToken.None
    test <@ count >= 3 @>
}

