/// The contract the server and the browser share: the side effect of keeping todos, and what the server tells the
/// client, as Orsak interfaces, a provider, and effects. [<GenRemote>] generates the proxy, TodoApiProxy, at the end.
module Todos.Shared.Contract

open System.Threading.Tasks
open Orsak
open Orsak.Remoting
open Orsak.Remoting.Callbacks

type Todo = { Id: int; Title: string; Done: bool }

/// The contract's errors, which cross the wire as values.
type TodoError =
    | EmptyTitle
    | NotFound of id: int
    | AlreadyDone of id: int

/// What the server tells the client: implemented by the client, called by the server, down the client's connection.
type ITodoEvents =
    /// The todos, changed by another client.
    abstract Changed: todos: Todo list -> System.Threading.Tasks.Task<unit>

/// Keeping todos, wherever it happens: on the server, a store; in the browser, calls to the server.
[<GenRemote>]
type ITodoApi =
    abstract List: unit -> Task<Todo list>
    abstract Add: title: string -> Task<Result<Todo, TodoError>>
    abstract Complete: id: int -> Task<Result<Todo, TodoError>>
    /// A connection, down which the server calls the client's ITodoEvents, until the client stops reading.
    abstract Connect: unit -> RemoteStream<Callback>

type ITodoApiProvider =
    abstract TodoApi: ITodoApi

/// The effects of the contract. An effect built from them doesn't know where it runs.
module TodoApi =
    let list () =
        Effect.Create(fun (p: #ITodoApiProvider) -> p.TodoApi.List())

    let add title =
        Effect.Create(fun (p: #ITodoApiProvider) -> p.TodoApi.Add title)

    let complete id =
        Effect.Create(fun (p: #ITodoApiProvider) -> p.TodoApi.Complete id)
